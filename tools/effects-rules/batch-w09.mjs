import { NUM, num } from "./lex.mjs";

export const rules = [
  // 「此技能微弱对手时技能先制+N」——「X时Y」省写（e48-24 的「若X则Y」形之外）。
  // 前半「此技能微弱对手时」的谓词由 condOf 的 effWeakVsFoe 承担；这里连同「技能先制+N」一起整段吃下，
  // 因为解析器不把「X时」切给负载（切开后「技能先制+3」是 no-rule）。
  { id: "w09-weak-prio-01",
    re: new RegExp(`^此技能微弱(?:对手|对方|敌方)时(?:技能)?先制([+＋])?${NUM}$`),
    go: (m) => ({ flags: { priorityIf: { when: { effWeakVsFoe: true }, add: num(m[2]) } } }) },

  // 「与对方翻转属性」——type_swap 计时标记（交换对称，标记在自身即可，到期还原）。
  // 「N回合内」由解析器的回合前缀剥成 turns，与 e53-v26-03 的 IR 一致。
  { id: "w09-typeswap-flip-01",
    re: /^与(?:对方|对手|敌方)翻转属性$/,
    go: () => ({ effects: [{ op: "apply_status", name: "type_swap", target: "self" }] }) },

  // 「克制倍数取自身对对手、对手对自身克制倍数中的最大值」——eff_max（结算见 ops/slots/w09.ts）。
  // 分段器在顿号处把它切成两段，本规则（整句形态）因此仍轮不到；两段各被 e47-08 留档。
  { id: "w09-effmax-01",
    re: /^克制倍数取自身对对手、对手对自身克制倍数中的最大值$/,
    go: () => ({ effects: [{ op: "eff_max", target: "self" }] }) },
];
